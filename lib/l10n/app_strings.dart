  static String forLanguage(String language, String key) {
    return _additionalValues[language]?[key] ??
        _values[language]?[key] ??
        _additionalValues['en']?[key] ??
        _values['en']![key] ??
        key;
  }

  static String text(String key) =>
      forLanguage(ThemeManager.instance.languageCode, key);
}

/// Rebuilds translated app labels whenever the user changes language without
/// forcing Flutter's Material widgets into an unsupported system locale.
class AppLanguageScope extends InheritedNotifier<ThemeManager> {
  AppLanguageScope({
    required super.child,
    super.key,
  }) : super(notifier: ThemeManager.instance);

  static String languageOf(BuildContext context) {
    return context
            .dependOnInheritedWidgetOfExactType<AppLanguageScope>()
            ?.notifier
            ?.languageCode ??
        'en';
  }
}

extension AppStringsContext on BuildContext {
  String tr(String key) =>
      AppStrings.forLanguage(AppLanguageScope.languageOf(this), key);
}
